import { chromium, shot } from './_pw.mjs';
import { boot } from './_boot.mjs';
const browser = await chromium.launch();
const { ctx, page } = await boot(browser);
const body = () => page.evaluate(() => document.body.innerText);
const style = () => page.evaluate(()=>{const id=localStorage.getItem('codex-active-id');const c=JSON.parse(localStorage.getItem('codex-character-'+id)||'{}');return JSON.stringify({fightingStyle:c.fightingStyle, feats:(c.feats||[]).map(f=>f.name||f)});});
console.log('before:', await style());
await page.locator('[data-fighting-style-gap]').first().click();
await page.waitForTimeout(1200);
console.log('options present:', await page.locator('[data-style-option]').count());
console.log('option names:', await page.evaluate(()=>[...document.querySelectorAll('[data-style-option]')].map(b=>b.getAttribute('data-style-option')).join(', ')));
const opt = page.locator('[data-style-option="Interception"]').first();
await opt.scrollIntoViewIfNeeded();
await opt.click({timeout:10000, force:true}).catch(e=>console.log('CLICKFAIL',String(e).slice(0,80)));
await page.waitForTimeout(1800);
await shot(page,'play-fighting-style-picked-390');
console.log('after pick:', await style());
console.log('gap band still present:', await page.locator('[data-fighting-style-gap]').count());
const t = await body();
const i = t.indexOf('REACTION');
console.log('REACTION band:', t.slice(i, i+420).replace(/\n/g,' | '));
console.log('Interception mentioned in page:', /Interception/.test(t));
await ctx.close(); await browser.close();
