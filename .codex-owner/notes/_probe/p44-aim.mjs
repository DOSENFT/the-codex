import { chromium, shot } from './_pw.mjs';
import { boot, goTab } from './_boot.mjs';
const AI_CFG = JSON.stringify({ provider:'ollama', ollamaUrl:'http://localhost:11434', ollamaModel:'gemma3-27b-abliterated:latest', fallbackEnabled:false });
const browser = await chromium.launch();
const { ctx, page } = await boot(browser, { extra: { 'codex-ai-config': AI_CFG } });
const body = () => page.evaluate(()=>document.body.innerText);
const diff=(a,b,n=1400)=>{const p=a.split('\n');return b.split('\n').filter(l=>l.trim()&&!p.includes(l)).join(' | ').slice(0,n);};
const idle = async(ms=240000)=>{const t0=Date.now();const b=page.getByRole('button',{name:/^Give me a beat$/}).first();while(Date.now()-t0<ms){if(await b.isEnabled().catch(()=>false))return Date.now()-t0;await page.waitForTimeout(1000);}return -1;};
await goTab(page,'session','Roleplay'); await page.waitForTimeout(1500);
await page.getByRole('button',{name:/Start the scene/i}).first().click(); await page.waitForTimeout(800);
await page.getByPlaceholder(/Around the campfire/i).fill('A crowded riverside tavern, rain outside');
await page.getByPlaceholder(/still being polite/i).fill('Tense. Scar is watching the door.');
await page.getByRole('button',{name:/That.{0,3}s the scene/i}).first().click();
await idle();
await page.getByPlaceholder(/Add a player/i).first().fill('Brenna');
await page.getByRole('button',{name:/^Add player$/i}).first().click();
await page.waitForTimeout(900);
console.log('=== table now ===');
const pre = await body();
const aim = page.getByRole('button',{name:/Aim a beat/i}).first();
console.log('Aim a beat present:', await aim.count(), 'label:', await aim.getAttribute('aria-label').catch(()=>''));
await aim.scrollIntoViewIfNeeded(); await aim.click({timeout:8000}).catch(e=>console.log('fail',String(e).slice(0,60)));
const t0=Date.now(); const ms = await idle();
await page.waitForTimeout(1500);
await shot(page,'play-roleplay-aim-a-beat-390');
const post = await body();
console.log(`aim result (waited ${Date.now()-t0}ms, idle=${ms}):`, diff(pre,post));
console.log('Brenna named in beat:', /Brenna/.test(post));
console.log('table storage:', await page.evaluate(()=>{const id=localStorage.getItem('codex-active-id');return (localStorage.getItem('codex-rp-table-'+id)||'').slice(0,300);}));
await ctx.close(); await browser.close();
