import { chromium, LIVE, PHONE, importFile, settle } from './rig.mjs';
import { realCopy } from './families.mjs';
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: PHONE, deviceScaleFactor: 3 });
const page = await ctx.newPage();
const bad = [];
const mark = s => bad.push('--- ' + s);
page.on('response', r => { if (r.status() >= 400) bad.push(`${r.status()}  ${r.url()}`); });
page.on('requestfailed', r => bad.push(`FAIL  ${r.url()}  ${r.failure()?.errorText}`));
mark('goto');
await page.goto(LIVE, { waitUntil: 'networkidle' }); await settle(page);
mark('import');
await importFile(page, realCopy('full')); await settle(page);
mark('settings');
await page.getByRole('button', { name: /Open settings/i }).first().click().catch(()=>{});
await page.waitForTimeout(1200);
mark('escape');
await page.keyboard.press('Escape').catch(()=>{}); await page.waitForTimeout(600);
mark('heal');
await page.getByRole('button', { name: /^Heal 5$/i }).first().click().catch(()=>{});
await page.waitForTimeout(1500);
console.log(bad.join('\n'));
await ctx.close(); await b.close();
